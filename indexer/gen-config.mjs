// Writes config.yaml from packages/shared/addresses.<chainId>.json, so addresses come from
// the deploy script and are never pasted by hand.
//   node gen-config.mjs            -> Monad Testnet via HyperSync (needs ENVIO_API_TOKEN)
//   RPC_ONLY=1 node gen-config.mjs -> Monad Testnet via public RPC only (no token)
//   node gen-config.mjs 31337      -> local anvil via RPC
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const chainId = process.argv[2] ?? "10143";
const d = JSON.parse(readFileSync(join(here, `../packages/shared/addresses.${chainId}.json`), "utf8"));
if (!d.DeliveryOracle) throw new Error(`no deployment in addresses.${chainId}.json`);

const rpc =
  chainId === "10143"
    ? `    rpc:
      - url: https://testnet-rpc.monad.xyz
        for: ${process.env.RPC_ONLY ? "sync" : "fallback"}`
    : `    rpc:
      - url: ${process.env.LOCAL_RPC ?? "http://host.docker.internal:8545"}
        for: sync`;

const events = {
  SeriesRegistry: [
    "SeriesCreated(uint256 indexed seriesId, address token, bytes32 gpu, bytes32 region, uint64 deliveryStart, uint64 deliveryEnd)",
    "MarkUpdated(uint256 indexed seriesId, uint128 price, uint64 scheduledAt)",
  ],
  BondVault: [
    "BondDeposited(address indexed provider, uint256 indexed seriesId, uint256 amount)",
    "Minted(address indexed provider, uint256 indexed seriesId, uint64 hrs)",
    "MarginCall(address indexed provider, uint256 indexed seriesId, uint256 shortfall)",
    "MarginCleared(address indexed provider, uint256 indexed seriesId)",
    "BondReleased(address indexed provider, uint256 indexed seriesId, uint256 amount)",
    "BondSlashed(address indexed provider, uint256 indexed seriesId, address indexed to, uint256 amount)",
    "BondRatioSet(address indexed provider, uint256 indexed seriesId, uint16 bondRatioBps)",
    "HoursSettled(address indexed provider, uint256 indexed seriesId, uint64 hrs)",
  ],
  RedemptionManager: [
    "Redeemed(uint256 indexed ticketId, uint256 indexed seriesId, address holder, address provider, uint32 hrs, uint128 priceAtOpen)",
    "TicketKeys(uint256 indexed ticketId, bytes32 holderKey, address probeKey, address nodeKey, uint64 accessDeadline)",
    "AccessPosted(uint256 indexed ticketId, bytes ciphertext)",
    "HoursConfirmed(uint256 indexed ticketId, uint32 hrs)",
    "HoursSlashed(uint256 indexed ticketId, uint32 hrs, uint256 payout)",
    "HoursDisputed(uint256 indexed ticketId, uint32 hrs)",
    "HourVerdict(uint256 indexed ticketId, uint32 hour, uint8 kind)",
    "TicketSettled(uint256 indexed ticketId)",
    "NodeKeySet(address indexed provider, address nodeKey)",
  ],
  DeliveryOracle: ["ReportReceived(uint64 indexed scheduledAt, uint32 verdicts, uint32 applied, uint32 marks, uint32 ratios, uint32 checks, bool relayed)"],
  SilicaBook: [
    "OrderPlaced(uint256 indexed orderId, uint256 indexed seriesId, address indexed owner, bool isBid, uint128 price, uint32 hrs)",
    "OrderCancelled(uint256 indexed orderId, uint256 indexed seriesId, uint32 remaining)",
    "Trade(uint256 indexed seriesId, uint256 indexed makerOrderId, address maker, address taker, bool takerBuys, uint32 hrs, uint128 price)",
  ],
};

let yaml = `# yaml-language-server: $schema=./node_modules/envio/evm.schema.json
# Generated by gen-config.mjs from packages/shared/addresses.${chainId}.json. Do not edit.
name: silica-indexer
field_selection:
  transaction_fields:
    - hash
contracts:
`;
for (const [name, evs] of Object.entries(events)) {
  yaml += `  - name: ${name}\n    handler: src/EventHandlers.ts\n    events:\n${evs.map((e) => `      - event: "${e}"`).join("\n")}\n`;
}
yaml += `chains:
  - id: ${chainId}
    start_block: ${d.deployBlock}
${rpc}
    contracts:
${Object.keys(events).map((n) => `      - name: ${n}\n        address: "${d[n]}"`).join("\n")}
`;
writeFileSync(join(here, "config.yaml"), yaml);
console.log(`wrote config.yaml for chain ${chainId} from block ${d.deployBlock}`);
