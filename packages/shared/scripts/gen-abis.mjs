// Extracts ABIs from Foundry artifacts into a typed `as const` module (wagmi-cli style).
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../../contracts/out");
const names = ["MockUSDC", "SilicaToken", "SeriesRegistry", "BondVault", "RedemptionManager", "DeliveryOracle", "SilicaBook"];

let src = "// Generated by scripts/gen-abis.mjs from contracts/out. Do not edit.\n\n";
for (const n of names) {
  const art = JSON.parse(readFileSync(join(out, `${n}.sol`, `${n}.json`), "utf8"));
  const key = n.charAt(0).toLowerCase() + n.slice(1);
  src += `export const ${key}Abi = ${JSON.stringify(art.abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(here, "../src/abis.ts"), src);
console.log("wrote", names.length, "ABIs");
